/** Phrase in a language, with {placeholders} filled. Falls back to German. */
export function say(lang, key, vars = {}) {
  const table = PHRASES[lang] || PHRASES.de;
  const text = table[key] ?? PHRASES.de[key];
  if (text == null) throw new Error(`missing phrase ${key}`);
  return typeof text === 'string' ? text.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? '')) : text;
}
